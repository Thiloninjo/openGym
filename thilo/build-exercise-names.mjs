#!/usr/bin/env node
// Thilos Fork: die deutschen Übungsnamen für den Coach-Hook (api/thilo-coach.js).
// Der API-Prozess läuft ohne frontend/ (Dockerfile, /opt/opengym/api), darum wird die Liste aus
// frontend/src/exercise-names/de.js nach api/thilo-exercise-names-de.js erzeugt und eingecheckt,
// wie scripts/build-coach-assets.mjs es mit dem Katalog macht.
//
//   node thilo/build-exercise-names.mjs           # schreiben
//   node thilo/build-exercise-names.mjs --check   # Fehler, wenn veraltet
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'frontend', 'src', 'exercise-names', 'de.js');
const out = join(root, 'api', 'thilo-exercise-names-de.js');
const { default: de } = await import(pathToFileURL(src).href);
const body = '/* GENERATED by thilo/build-exercise-names.mjs from frontend/src/exercise-names/de.js — do not edit. */\n' +
  'export const DE_NAMES = ' + JSON.stringify(de) + ';\n';
if (process.argv.includes('--check')) {
  let cur = null;
  try { cur = readFileSync(out, 'utf8'); } catch { /* fehlt = veraltet */ }
  if (cur?.replace(/\r\n/g, '\n') !== body) {   // ein Checkout mit CRLF zählt als aktuell
    console.error('api/thilo-exercise-names-de.js ist veraltet — node thilo/build-exercise-names.mjs'); process.exit(1); }
  console.log(`api/thilo-exercise-names-de.js aktuell (${Object.keys(de).length} Namen).`);
} else {
  writeFileSync(out, body);
  console.log(`api/thilo-exercise-names-de.js geschrieben (${Object.keys(de).length} Namen).`);
}
